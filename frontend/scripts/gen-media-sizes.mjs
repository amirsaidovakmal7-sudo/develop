#!/usr/bin/env node
/**
 * Writes src/data/mediaSizes.generated.ts — the intrinsic pixel size of every
 * project still under src/assets/projects/.
 *
 * The case view shows screenshots uncropped at their own aspect ratio, so
 * without this the page would reflow as each one decodes. Reading the sizes
 * at build time lets every <img> carry width/height and reserve its box.
 *
 * Usage: node scripts/gen-media-sizes.mjs
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const PROJECTS_DIR = path.join(ROOT, 'src', 'assets', 'projects');
const OUT = path.join(ROOT, 'src', 'data', 'mediaSizes.generated.ts');

const sizes = {};

for (const projectId of readdirSync(PROJECTS_DIR).sort()) {
  const dir = path.join(PROJECTS_DIR, projectId);
  if (!statSync(dir).isDirectory()) continue;

  for (const file of readdirSync(dir).sort()) {
    if (!file.endsWith('.webp')) continue;
    const { width, height } = await sharp(path.join(dir, file)).metadata();
    sizes[`${projectId}/${file}`] = [width, height];
  }
}

const body = Object.entries(sizes)
  .map(([key, [w, h]]) => `  '${key}': [${w}, ${h}],`)
  .join('\n');

writeFileSync(
  OUT,
  `// AUTO-GENERATED by scripts/gen-media-sizes.mjs — do not edit by hand.
// Intrinsic [width, height] of every project still, keyed by "<project>/<file>".
export const MEDIA_SIZES: Record<string, [number, number]> = {
${body}
};
`,
  'utf8',
);

console.log(`wrote ${Object.keys(sizes).length} entries to ${path.relative(ROOT, OUT)}`);
